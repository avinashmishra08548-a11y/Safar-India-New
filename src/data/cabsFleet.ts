export function buildDynamicFleetList(adminConfig?: { vehicles?: Record<string, any> } | null): CabVehicle[] {
  const cfgVehicles = adminConfig?.vehicles || {};
  const result: CabVehicle[] = [];
  const seen = new Set<string>();

  for (const baseCab of CABS_FLEET) {
    seen.add(baseCab.id);
    const override = cfgVehicles[baseCab.id];
    if (override && override.enabled === false) continue;
    result.push(
      override
        ? {
            ...baseCab,
            name: override.name || baseCab.name,
            models: override.models || baseCab.models,
            category: override.category || baseCab.category,
            ratePerKm: Number(override.ratePerKm ?? baseCab.ratePerKm),
            roundTripRatePerKm: Number(override.roundTripRatePerKm ?? baseCab.roundTripRatePerKm),
            extraKmRate: Number(override.extraKmRate ?? baseCab.extraKmRate),
            minKm: Number(override.minKm ?? baseCab.minKm),
            minFare: Number(override.minFare ?? baseCab.minFare),
            driverAllowancePerDay: Number(override.driverAllowancePerDay ?? baseCab.driverAllowancePerDay),
            waitingChargePerHour: Number(override.waitingChargePerHour ?? baseCab.waitingChargePerHour),
            nightAllowance: Number(override.nightAllowance ?? baseCab.nightAllowance),
            hillStationCharge: Number(override.hillStationCharge ?? baseCab.hillStationCharge),
            difficultMountainCharge: Number(override.difficultMountainCharge ?? baseCab.difficultMountainCharge),
            local8Hr80KmFare: Number(override.local8Hr80KmFare ?? baseCab.local8Hr80KmFare),
            capacityPassengers: Number(override.capacityPassengers ?? baseCab.capacityPassengers),
            capacityLuggage: Number(override.capacityLuggage ?? baseCab.capacityLuggage),
            popular: override.popular !== undefined ? Boolean(override.popular) : baseCab.popular,
            enabled: true
          }
        : baseCab
    );
  }

  // Append Admin-created custom vehicles
  for (const [vehId, override] of Object.entries(cfgVehicles)) {
    if (seen.has(vehId) || !override || override.enabled === false) continue;
    result.push({
      id: vehId,
      name: override.name || vehId,
      models: override.models || 'Custom AC Fleet',
      category: override.category || 'Custom Fleet Category',
      ratePerKm: Number(override.ratePerKm || 12),
      roundTripRatePerKm: Number(override.roundTripRatePerKm || 14),
      extraKmRate: Number(override.extraKmRate || 13),
      minKm: Number(override.minKm || 130),
      minFare: Number(override.minFare || 1800),
      driverAllowancePerDay: Number(override.driverAllowancePerDay || 300),
      waitingChargePerHour: Number(override.waitingChargePerHour || 150),
      nightAllowance: Number(override.nightAllowance || 150),
      statePermitTax: Number(override.statePermitTax || 250),
      hillStationCharge: Number(override.hillStationCharge || 400),
      difficultMountainCharge: Number(override.difficultMountainCharge || 900),
      local8Hr80KmFare: Number(override.local8Hr80KmFare || 2200),
      capacityPassengers: Number(override.capacityPassengers || 4),
      capacityLuggage: Number(override.capacityLuggage || 3),
      features: ['Chilled AC', 'Verified Commercial Chauffeur', 'Custom Route Package'],
      popular: Boolean(override.popular),
      enabled: true,
      isCustom: true,
      image: fleetShowcaseImg,
      description: override.models || 'Custom AC vehicle configured in Fleet Control Center.'
    });
  }

  return result;
}

