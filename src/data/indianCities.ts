// Haversine formula with highway detour coefficient (1.28x) for non-cached pairs
function calculateHaversineKm(lat1: number, lon1: number, lat2: number, lon2: number): number {
  const R = 6371; // Earth radius in km
  const dLat = (lat2 - lat1) * (Math.PI / 180);
  const dLon = (lon2 - lon1) * (Math.PI / 180);
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos(lat1 * (Math.PI / 180)) * Math.cos(lat2 * (Math.PI / 180)) *
    Math.sin(dLon / 2) * Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  const crowDistance = R * c;
  // Highway road route detour factor for Indian national highways
  return Math.round(crowDistance * 1.28);
}

function normalizeCityStr(str: string): string {
  return str.toLowerCase().replace(/[^a-z]/g, '');
}

export function estimateDistanceKm(fromCity: string, toCity: string): number {
  if (!fromCity || !toCity) return 150;
  if (fromCity.trim().toLowerCase() === toCity.trim().toLowerCase()) return 40;

  const nFrom = normalizeCityStr(fromCity);
  const nTo = normalizeCityStr(toCity);

  // Check direct pairs
  for (const [key, km] of Object.entries(VERIFIED_HIGHWAY_PAIRS)) {
    const [p1, p2] = key.split('-');
    if (
      (nFrom.includes(p1) || p1.includes(nFrom)) &&
      (nTo.includes(p2) || p2.includes(nTo))
    ) {
      return km;
    }
  }

  // Find coordinates in POPULAR_INDIAN_CITIES
  const cityA = POPULAR_INDIAN_CITIES.find(c => 
    normalizeCityStr(c.name).includes(nFrom) || nFrom.includes(normalizeCityStr(c.name))
  );
  const cityB = POPULAR_INDIAN_CITIES.find(c => 
    normalizeCityStr(c.name).includes(nTo) || nTo.includes(normalizeCityStr(c.name))
  );

  if (cityA && cityB) {
    const calc = calculateHaversineKm(cityA.lat, cityA.lon, cityB.lat, cityB.lon);
    return Math.max(70, calc);
  }

  // Reasonable intercity fallback
  return 180;
}

