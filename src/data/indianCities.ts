export function isHillAreaToken(str: string): boolean {
  const norm = (str || '').toLowerCase().replace(/[^a-z]/g, '');
  if (!norm) return false;
  return HILL_TERRAIN_TOKENS.some((t) => norm.includes(t));
}

function normalizeCityStr(str: string): string {
  return (str || '').toLowerCase().replace(/[^a-z]/g, '');
}

/**
 * Checks if two locations match a verified Indian highway or hill route pair
 */
export function lookupVerifiedHighwayDistance(fromCity: string, toCity: string): number | null {
  if (!fromCity || !toCity) return null;
  const nFrom = normalizeCityStr(fromCity);
  const nTo = normalizeCityStr(toCity);
  if (!nFrom || !nTo) return null;

  for (const [key, km] of Object.entries(VERIFIED_HIGHWAY_PAIRS)) {
    const [p1, p2] = key.split('-');
    if (nFrom.includes(p1) && nTo.includes(p2)) {
      return km;
    }
  }
  return null;
}

// Haversine formula with terrain-aware road winding coefficient (1.28x plains, 1.58x one-end hill, 2.04x mountain-to-mountain)
export function calculateTerrainHaversineKm(
  lat1: number,
  lon1: number,
  lat2: number,
  lon2: number,
  fromCity = '',
  toCity = ''
): number {
  const R = 6371; // Earth radius in km
  const dLat = (lat2 - lat1) * (Math.PI / 180);
  const dLon = (lon2 - lon1) * (Math.PI / 180);
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos(lat1 * (Math.PI / 180)) *
      Math.cos(lat2 * (Math.PI / 180)) *
      Math.sin(dLon / 2) *
      Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  const crowDistance = R * c;

  const fromHill = isHillAreaToken(fromCity);
  const toHill = isHillAreaToken(toCity);

  let detourFactor = 1.28;
  if (fromHill && toHill) {
    // Deep mountain-to-mountain winding roads (e.g., Rudraprayag to Nainital: 109.2 km crow * 2.042 = 223 km)
    detourFactor = 2.042;
  } else if (fromHill || toHill) {
    // Plains to hill climb ghat roads
    detourFactor = 1.58;
  } else if (crowDistance < 100) {
    detourFactor = 1.32;
  }

  return Math.max(25, Math.round(crowDistance * detourFactor));
}

export function estimateDistanceKm(fromCity: string, toCity: string): number {
  if (!fromCity || !toCity) return 150;
  if (fromCity.trim().toLowerCase() === toCity.trim().toLowerCase()) return 40;

  const verifiedKm = lookupVerifiedHighwayDistance(fromCity, toCity);
  if (verifiedKm !== null) {
    return verifiedKm;
  }

  const nFrom = normalizeCityStr(fromCity);
  const nTo = normalizeCityStr(toCity);

  // Find coordinates in POPULAR_INDIAN_CITIES
  const cityA = POPULAR_INDIAN_CITIES.find(
    (c) =>
      normalizeCityStr(c.name).includes(nFrom) ||
      nFrom.includes(normalizeCityStr(c.name.split('(')[0]))
  );
  const cityB = POPULAR_INDIAN_CITIES.find(
    (c) =>
      normalizeCityStr(c.name).includes(nTo) ||
      nTo.includes(normalizeCityStr(c.name.split('(')[0]))
  );

  if (cityA && cityB) {
    const calc = calculateTerrainHaversineKm(
      cityA.lat,
      cityA.lon,
      cityB.lat,
      cityB.lon,
      fromCity,
      toCity
    );
    return Math.max(40, calc);
  }

  // Reasonable intercity fallback
  return 180;
}

